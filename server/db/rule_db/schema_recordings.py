"""programs・recordings のテーブルを作る（init_db の一部）"""

class _RecordingTablesMixin:
    """programs・recordings のテーブルを作る（init_db の一部）"""

    def _create_programs_recordings(self, conn):
        """予約(programs)と録画(recordings)の表。"""
        conn.execute("""
            CREATE TABLE IF NOT EXISTS programs (
                id                INTEGER PRIMARY KEY,
                reserve_id        INTEGER UNIQUE,
                reserve_key       TEXT,
                original_title    TEXT,
                station_name      TEXT,
                start_time        TEXT,
                expected_end_time TEXT,
                text_parser_result   TEXT,
                original_description  TEXT,
                original_extended_info TEXT,
                state             TEXT NOT NULL DEFAULT 'pending',
                error_message     TEXT,
                parser_error      TEXT,
                start_margin      INTEGER,
                end_margin        INTEGER,
                title             TEXT,
                folder            TEXT,
                episode_name      TEXT,
                episode_number    TEXT,
                category          TEXT,
                furigana          TEXT,
                else_info         TEXT,
                auto_send         INTEGER,
                is_text_parser    INTEGER,
                app_output_path   TEXT,
                app_output_path_format TEXT,
                setting           TEXT,
                genre             TEXT,
                video_info        TEXT,
                audio_info        TEXT,
                edcb_tag          TEXT,
                server_url        TEXT,
                auto_skip_reason  TEXT,
                created_at        TEXT NOT NULL,
                updated_at        TEXT NOT NULL
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS recordings (
                id               INTEGER PRIMARY KEY,
                program_id       INTEGER REFERENCES programs(id) ON DELETE CASCADE,
                rec_id           INTEGER,
                onid             INTEGER,
                tsid             INTEGER,
                sid              INTEGER,
                eid              INTEGER,
                state            TEXT NOT NULL DEFAULT 'pending',
                shimakaze_job_id INTEGER,
                output_path      TEXT,
                error_message    TEXT,
                parser_error     TEXT,
                title            TEXT,
                folder           TEXT,
                episode_number   TEXT,
                episode_name     TEXT,
                category         TEXT,
                eit_title        TEXT,
                eit_description  TEXT,
                eit_extended_info TEXT,
                eit_start_time   TEXT,
                eit_end_time     TEXT,
                eit_station_name TEXT,
                edcb_ts_path     TEXT,
                host_ts_path     TEXT,
                app_ts_path      TEXT,
                amatsukaze_ts_path TEXT,
                konomitv_ts_path TEXT,
                drop_error            TEXT,
                file_exist            INTEGER,
                recording_start_time  TEXT,
                recording_end_time    TEXT,
                rec_status            INTEGER,
                rec_comment           TEXT,
                furigana              TEXT,
                auto_send             TEXT,
                else_info             TEXT,
                is_text_parser        INTEGER,
                app_output_path       TEXT,
                app_output_path_format TEXT,
                encode_dir            TEXT,
                setting               TEXT,
                eit_genre             TEXT,
                eit_video_info        TEXT,
                eit_audio_info        TEXT,
                file_size             INTEGER,
                duration_sec          REAL,
                text_parser_result    TEXT,
                segments              TEXT,
                edcb_tag              TEXT,
                server_url            TEXT,
                probe_result          TEXT,
                eit_overlap           REAL,
                comments_json         TEXT,
                comment_count         INTEGER,
                captions_json         TEXT,
                captions2_json        TEXT,
                key_frames            TEXT,
                frame_table           TEXT,
                cm_analysis           TEXT,
                tmp_dirs              TEXT,
                to_encode_info        TEXT,
                rec_drops             INTEGER DEFAULT 0,
                rec_scrambles         INTEGER DEFAULT 0,
                auto_add_id           INTEGER,
                created_at       TEXT NOT NULL,
                updated_at       TEXT NOT NULL DEFAULT ''
            )
        """)
